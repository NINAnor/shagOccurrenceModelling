#' Save essential outputs from an inlabru habitat model analysis
#'
#' Saves:
#'   1. Summary of all fitted models
#'   2. WAIC/model comparison table
#'   3. Best fitted model
#'   4. Predictions from the best model
#'   5. Prediction plot from the best model
#'   6. Session information
#'
#' @param results List returned by run_shag_inla_model()
#' @param out_dir Output directory
#' @param prefix File name prefix
#'
#' @return Character vector of saved files
#' @export

save_inla_results <- function(results,
                              out_dir,
                              prefix = "inla_model") {

  library(sf)
  library(ggplot2)

  dir.create(
    out_dir,
    recursive = TRUE,
    showWarnings = FALSE
  )

  saved <- character()

  #--------------------------------------------------
  # Save summaries of all fitted models
  #--------------------------------------------------

  model_names <- c(
    "fit_spatial",
    "fit_nospatial",
    "fit_nospatialindividual"
  )

  for (nm in model_names) {

    fit <- results[[nm]]

    if (!is.null(fit)) {

      summary_file <- file.path(
        out_dir,
        paste0(prefix, "_", nm, "_summary.txt")
      )

      capture.output(
        summary(fit),
        file = summary_file
      )

      saved <- c(saved, summary_file)
    }
  }

  #--------------------------------------------------
  # Save WAIC/model comparison
  #--------------------------------------------------

  if (!is.null(results$waic)) {

    waic_file <- file.path(
      out_dir,
      paste0(prefix, "_model_summary.csv")
    )

    waic_df <- data.frame(
      Model = names(results$waic),
      WAIC = as.numeric(results$waic)
    )

    write.csv(
      waic_df,
      waic_file,
      row.names = FALSE
    )

    saved <- c(saved, waic_file)
  }

  #--------------------------------------------------
  # Save best fitted model
  #--------------------------------------------------

  if (!is.null(results$best_model_name)) {

    best_fit <- results[[results$best_model_name]]

    if (!is.null(best_fit)) {

      best_model_file <- file.path(
        out_dir,
        paste0(prefix, "_best_model.rds")
      )

      saveRDS(
        best_fit,
        best_model_file
      )

      saved <- c(saved, best_model_file)
    }
  }

  #--------------------------------------------------
  # Determine prediction object and plot
  #--------------------------------------------------

  pred <- switch(
    results$best_model_name,
    fit_spatial = results$pred_full,
    fit_nospatial = results$pred_dh,
    fit_nospatialindividual = results$pred_dh,
    NULL
  )

  plot_obj <- switch(
    results$best_model_name,
    fit_spatial = results$plot_full,
    fit_nospatial = results$plot_dh,
    fit_nospatialindividual = results$plot_dh,
    NULL
  )

  #--------------------------------------------------
  # Save predictions
  #--------------------------------------------------

  if (inherits(pred, "sf")) {

    pred_file <- file.path(
      out_dir,
      paste0(prefix, "_best_predictions.gpkg")
    )

    sf::st_write(
      pred,
      pred_file,
      delete_dsn = TRUE,
      quiet = TRUE
    )

    saved <- c(saved, pred_file)
  }

  #--------------------------------------------------
  # Save prediction plot
  #--------------------------------------------------

  if (inherits(plot_obj, "ggplot")) {

    png_file <- file.path(
      out_dir,
      paste0(prefix, "_best_prediction.png")
    )

    pdf_file <- file.path(
      out_dir,
      paste0(prefix, "_best_prediction.pdf")
    )

    ggplot2::ggsave(
      filename = png_file,
      plot = plot_obj,
      width = 10,
      height = 8,
      dpi = 300,
      bg = "white"
    )

    ggplot2::ggsave(
      filename = pdf_file,
      plot = plot_obj,
      width = 10,
      height = 8,
      bg = "white"
    )

    saved <- c(saved, png_file, pdf_file)
  }

  #--------------------------------------------------
  # Save session information
  #--------------------------------------------------

  session_file <- file.path(
    out_dir,
    paste0(prefix, "_sessionInfo.txt")
  )

  capture.output(
    sessionInfo(),
    file = session_file
  )

  saved <- c(saved, session_file)

  invisible(unique(saved))
}


#' Save outputs from an inlabru habitat model analysis
#'
#' Saves fitted model objects, summaries, model selection metrics,
#' spatial objects, prediction surfaces, publication-quality figures,
#' and session information generated by `run_shag_inla_model()`.
#'
#' The function creates a complete archive of an analysis, allowing
#' model results to be reproduced, inspected, or reused without
#' refitting the computationally intensive INLA models.
#'
#' @param results A named list returned by
#'   `run_shag_inla_model()`.
#'
#' @param out_dir Directory where all outputs will be written.
#' The directory is created if it does not already exist.
#'
#' @param prefix Character string used as a prefix for all output files.
#'
#' @details
#'
#' The following outputs are saved when available:
#'
#' \itemize{
#'
#' \item Complete results object (`.rds`)
#'
#' \item Individual fitted model objects (`.rds`)
#'
#' \item Human-readable model summaries (`.txt`)
#'
#' \item WAIC comparison table (`.csv`)
#'
#' \item SPDE mesh (`.rds`)
#'
#' \item Presence locations (`.gpkg`)
#'
#' \item Predicted relative intensity surfaces (`.gpkg`)
#'
#' \item Publication-quality prediction figures (`.png` and `.pdf`)
#'
#' \item Session information (`sessionInfo()`) for reproducibility
#'
#' }
#'
#' Spatial outputs are written as GeoPackage files to preserve
#' coordinate reference systems and spatial attributes.
#'
#' Figures are exported as both high-resolution PNG (300 dpi) for
#' manuscripts and PDF for vector-based editing.
#'
#' Recording the R session information ensures that package versions
#' used during model fitting are archived alongside the results,
#' facilitating long-term reproducibility.
#'
#' @return
#' A character vector containing the paths of all files successfully
#' written to disk.
#'
#' @seealso
#' \code{\link{run_shag_inla_model}}
#'
#' @references
#' Pebesma E (2018).
#' Simple Features for R: Standardized Support for Spatial Vector Data.
#' *The R Journal*, **10**, 439--446.
#'
#' Wickham H (2016).
#' *ggplot2: Elegant Graphics for Data Analysis.*
#' Springer, New York.
#'
#' Bachl FE, Lindgren F, Borchers DL, Illian JB (2019).
#' inlabru: An R package for Bayesian spatial modelling from ecological
#' survey data.
#' *Methods in Ecology and Evolution*, **10**, 760--766.
#'
#' @export

save_inla_results_old <- function(results,
                              out_dir,
                              prefix = "inla_model") {

  library(sf)
  library(ggplot2)

  dir.create(
    out_dir,
    recursive = TRUE,
    showWarnings = FALSE
  )

  saved <- character()

  #--------------------------------------------------
  # Save complete object
  #--------------------------------------------------

  rds_file <- file.path(
    out_dir,
    paste0(prefix, "_results.rds")
  )

  saveRDS(results, rds_file)

  saved <- c(saved, rds_file)

  #--------------------------------------------------
  # Save model summaries
  #--------------------------------------------------

  if (!is.null(results$fit_spatial)) {

    txt_file <- file.path(
      out_dir,
      paste0(prefix, "_spatial_summary.txt")
    )

    capture.output(
      summary(results$fit_spatial),
      file = txt_file
    )

    saved <- c(saved, txt_file)

    saveRDS(
      results$fit_spatial,
      file.path(
        out_dir,
        paste0(prefix, "_fit_spatial.rds")
      )
    )
  }

  if (!is.null(results$fit_nospatial)) {

    txt_file <- file.path(
      out_dir,
      paste0(prefix, "_nospatial_summary.txt")
    )

    capture.output(
      summary(results$fit_nospatial),
      file = txt_file
    )

    saved <- c(saved, txt_file)

    saveRDS(
      results$fit_nospatial,
      file.path(
        out_dir,
        paste0(prefix, "_fit_nospatial.rds")
      )
    )
  }

  if (!is.null(results$fit_nospatialindividual)) {

    txt_file <- file.path(
      out_dir,
      paste0(prefix, "_nospatialindividual_summary.txt")
    )

    capture.output(
      summary(results$fit_nospatialindividual),
      file = txt_file
    )

    saved <- c(saved, txt_file)

    saveRDS(
      results$fit_nospatialindividual,
      file.path(
        out_dir,
        paste0(prefix, "_fit_nospatialindividual.rds")
      )
    )
  }

  #--------------------------------------------------
  # Save WAIC table
  #--------------------------------------------------

  if (!is.null(results$waic)) {

    waic_file <- file.path(
      out_dir,
      paste0(prefix, "_waic.csv")
    )

    waic_df <- data.frame(
      model = names(results$waic),
      WAIC = as.numeric(results$waic)
    )

    write.csv(
      waic_df,
      waic_file,
      row.names = FALSE
    )

    saved <- c(saved, waic_file)
  }

  #--------------------------------------------------
  # Save mesh
  #--------------------------------------------------

  if (!is.null(results$mesh)) {

    saveRDS(
      results$mesh,
      file.path(
        out_dir,
        paste0(prefix, "_mesh.rds")
      )
    )
  }

  #--------------------------------------------------
  # Save presence data
  #--------------------------------------------------

  if (!is.null(results$presences) &&
      inherits(results$presences, "sf")) {

    pres_file <- file.path(
      out_dir,
      paste0(prefix, "_presences.gpkg")
    )

    sf::st_write(
      results$presences,
      pres_file,
      delete_dsn = TRUE,
      quiet = TRUE
    )

    saved <- c(saved, pres_file)
  }

  #--------------------------------------------------
  # Save prediction surfaces
  #--------------------------------------------------

  save_sf_prediction <- function(x, stem) {

    if (!inherits(x, "sf")) {
      return(NULL)
    }

    file <- file.path(
      out_dir,
      paste0(prefix, "_", stem, ".gpkg")
    )

    sf::st_write(
      x,
      file,
      delete_dsn = TRUE,
      quiet = TRUE
    )

    file
  }

  if (!is.null(results$pred_dh)) {

    saved <- c(
      saved,
      save_sf_prediction(
        results$pred_dh,
        "pred_distHarvest"
      )
    )
  }

  if (!is.null(results$pred_full)) {

    saved <- c(
      saved,
      save_sf_prediction(
        results$pred_full,
        "pred_full"
      )
    )
  }

  #--------------------------------------------------
  # Save plots
  #--------------------------------------------------

  save_plot <- function(plot_obj, stem) {

    if (!inherits(plot_obj, "ggplot")) {
      return(character())
    }

    png_file <- file.path(
      out_dir,
      paste0(prefix, "_", stem, ".png")
    )

    pdf_file <- file.path(
      out_dir,
      paste0(prefix, "_", stem, ".pdf")
    )

    ggsave(
      png_file,
      plot_obj,
      width = 10,
      height = 8,
      dpi = 300
    )

    ggsave(
      pdf_file,
      plot_obj,
      width = 10,
      height = 8
    )

    c(png_file, pdf_file)
  }

  saved <- c(
    saved,
    save_plot(results$plot_dh, "distHarvest_plot"),
    save_plot(results$plot_full, "full_prediction_plot")
  )

  #--------------------------------------------------
  # Save session info
  #--------------------------------------------------

  session_file <- file.path(
    out_dir,
    paste0(prefix, "_sessionInfo.txt")
  )

  capture.output(
    sessionInfo(),
    file = session_file
  )

  saved <- c(saved, session_file)

  #--------------------------------------------------
  # Add metadata
  #--------------------------------------------------
  metadata <- list(
    created = Sys.time(),
    best_model = results$best_model_name,
    waic = results$waic,
    R_version = R.version.string
  )

  saveRDS(
    metadata,
    file.path(out_dir, paste0(prefix, "_metadata.rds"))
  )

  unique(saved)
}
